// Package serialization 提供框架内部的消息编解码与字段读写能力。
//
// 数值读写使用 Go 1.27 泛型方法，Integer 和 Float 支持相同底层类型的自定义类型。
// WriteInteger 和 ReadInteger 仅接受固定宽度整数；通用 Write/Read 中的 int、uint 统一编码为 8 字节。
// 数值采用大端序，浮点数采用 IEEE 754，字符串、切片、数组和 map 使用 uint32 长度前缀。
//
// Reader 和 Writer 不依赖消息注册表或外部 Codec。结构体实现 MessageCodec 时使用自身的编解码逻辑，
// 否则按声明顺序读写导出字段。消息注册、类型标识和外部 Codec 由 VividCodec 单独处理。
// 类型元数据会被缓存，字段访问不会逐项重新装箱。nil 指针和 nil 接口无法表示，写入时返回错误。
// 类型缓存按进程生命周期保留，不适合持续创建大量动态结构体类型。
// 此格式不含字段名和结构体类型标识，不支持循环引用，读写双方应使用一致的类型布局。
// 字段回退不等于远程消息自动注册：VividCodec.Encode/Decode 仍需消息注册或外部 Codec。
//
// 首次错误会保留，后续操作不再继续；失败前的字段可能已更新，解码不是事务操作。
// Reader 可复用目标切片的容量，会更新目标原有的别名视图；字节切片和字符串不会借用输入缓冲。
// 不应在需要保留旧值时复用同一目标。nil 和空集合均编码为零长度，不保留两者的区别。
// Writer.Bytes 返回当前缓冲的视图，继续写入可能改变该视图；归还 Writer 后框架不会复用该底层缓冲，
// 已返回的数据可继续由网络层持有。Reader/Writer 实例本身不可并发使用，也不可在归还后继续使用。
